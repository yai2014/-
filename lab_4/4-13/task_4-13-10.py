# Программа для нахождения суммы всех элементов с нечетными индексами в массиве

# Ввод размера массива
N = int(input("Введите размер массива N: "))

# Проверка на корректность ввода
if N <= 0:
    print("Ошибка: N должно быть > 0!")
else:
    # Создание массива
    A = []
    
    # Ввод элементов массива и вычисление суммы элементов с нечетными индексами
    S = 0
    i = 1  # Индексация с 1 (соответствует блок-схеме)
    while i <= N:
        element = float(input(f"Введите элемент A[{i}]: "))
        A.append(element)
        
        # Проверка, является ли индекс нечетным
        if i % 2 != 0:
            S = S + element
        
        i = i + 1
    
    # Вывод результата
    print(f"Массив: {A}")
    print(f"Сумма элементов с нечетными индексами (индексация с 1): {S}")