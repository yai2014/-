# Программа для нахождения суммы всех нечетных элементов в массиве

# Ввод размера массива
N = int(input("Введите размер массива N: "))

# Проверка на корректность ввода
if N <= 0:
    print("Ошибка: N должно быть > 0!")
else:
    # Создание массива
    A = []
    
    # Ввод элементов массива и вычисление суммы нечетных элементов
    S = 0
    i = 1
    while i <= N:
        element = float(input(f"Введите элемент A[{i}]: "))
        A.append(element)
        
        # Проверка, является ли элемент нечетным
        if element % 2 != 0:
            S = S + element
        
        i = i + 1
    
    # Вывод результата
    print(f"Массив: {A}")
    print(f"Сумма нечетных элементов: {S}")