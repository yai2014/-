# Программа для нахождения среднего арифметического среди элементов с четными индексами в массиве

# Ввод размера массива
N = int(input("Введите размер массива N: "))

# Проверка на корректность ввода
if N <= 0:
    print("Ошибка: N должно быть > 0!")
else:
    # Создание массива
    A = []
    
    # Ввод элементов массива и вычисление суммы и количества элементов с четными индексами
    S = 0
    count = 0
    i = 1  # Индексация с 1 (соответствует блок-схеме)
    
    while i <= N:
        element = float(input(f"Введите элемент A[{i}]: "))
        A.append(element)
        
        # Проверка, является ли индекс четным
        if i % 2 == 0:
            S = S + element
            count = count + 1
        
        i = i + 1
    
    # Проверка наличия элементов с четными индексами и вычисление среднего
    if count > 0:
        Avg = S / count
        print(f"Массив: {A}")
        print(f"Сумма элементов с четными индексами: {S}")
        print(f"Количество элементов с четными индексами: {count}")
        print(f"Среднее арифметическое: {Avg}")
    else:
        print(f"Массив: {A}")
        print("Нет элементов с четными индексами!")