 
N = int(input("Введите количество натуральных чисел N: "))

# Проверка на корректность ввода
if N < 1:
    print("Ошибка: N должно быть ≥ 1!")
else:
    # Начальные значения
    S = 0
    i = 1
    
    # Цикл для вычисления суммы
    while i <= N:
        S = S + i
        i = i + 1
    
    # Вывод результата
    print(f"Сумма первых {N} натуральных чисел: 1 + 2 + ... + {N} = {S}")