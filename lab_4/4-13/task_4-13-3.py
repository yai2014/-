 
N = int(input("Введите целое неотрицательное число N: "))

# Проверка на отрицательное число
if N < 0:
    print("Ошибка: Факториал не определён для отрицательных чисел!")
else:
    # Начальные значения
    F = 1
    i = 1
    
    # Цикл для вычисления факториала
    while i <= N:
        F = F * i
        i = i + 1
    
    # Вывод результата
    print(f"{N}! = {F}")