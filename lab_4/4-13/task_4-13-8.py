
# Программа для нахождения количества положительных чисел в массиве

# Ввод размера массива
N = int(input("Введите размер массива N: "))

# Проверка на корректность ввода
if N <= 0:
    print("Ошибка: N должно быть > 0!")
else:
    # Создание массива
    A = []
    
    # Ввод элементов массива и подсчёт положительных чисел
    count = 0
    i = 1
    while i <= N:
        element = float(input(f"Введите элемент A[{i}]: "))
        A.append(element)
        
        # Проверка, является ли элемент положительным
        if element > 0:
            count = count + 1
        
        i = i + 1
    
    # Вывод результата
    print(f"Массив: {A}")
    print(f"Количество положительных чисел в массиве: {count}")