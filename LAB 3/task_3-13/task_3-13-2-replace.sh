#!/bin/bash
echo "=========================================="
echo "     ЗАМЕНА ПРОБЕЛОВ НА ТАБУЛЯЦИЮ"
echo "=========================================="

if [ ! -f "sequences.txt" ]; then
    echo "Ошибка: Файл sequences.txt не найден!"
    exit 1
fi
echo "Содержимое ДО замены:"
echo "------------------------------------------"
cat sequences.txt
echo "------------------------------------------"
cp sequences.txt sequences.txt.bak
echo "Создана резервная копия: sequences.txt.bak"

sed -i 's/ /\t/g' sequences.txt
if [ $? -eq 0 ]; then
    echo "Замена выполнена успешно!"
    echo ""
    echo "Содержимое ПОСЛЕ замены:"
    echo "------------------------------------------"
    cat sequences.txt
    echo "------------------------------------------"
    
    # Показываем символы табуляции (для наглядности)
    echo ""
    echo "Проверка (табуляция отображается как ^I):"
    cat -T sequences.txt
else
    echo "Ошибка при выполнении замены!"
    exit 1
fi

echo "=========================================="

