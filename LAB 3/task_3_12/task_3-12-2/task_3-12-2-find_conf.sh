#!/bin/bash

echo "=========================================="
echo "     ПОИСК .CONF ФАЙЛОВ В ДИРЕКТОРИИ /etc"
echo "=========================================="
echo ""
echo "Список файлов с расширением .conf (без учёта регистра):"
echo "------------------------------------------"

ls -l /etc | grep -i '\.conf$'

if [ $? -eq 0 ]; then
    echo "------------------------------------------"
    echo "Поиск завершён. Файлы найдены."
else
    echo "------------------------------------------"
    echo "Файлы с расширением .conf не найдены."
fi

echo "=========================================="
