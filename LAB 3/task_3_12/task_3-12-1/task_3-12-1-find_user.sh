#!/bin/bash

echo "=========================================="
echo "     ПОИСК ПОЛЬЗОВАТЕЛЯ В /etc/passwd"
echo "=========================================="

echo "Имя текущего пользователя: $USER"
echo ""
echo "Результат поиска:"
echo "------------------------------------------"

grep "^$USER:" /etc/passwd

if [ $? -eq 0 ]; then
    echo "------------------------------------------"
    echo "Пользователь $USER найден в системе."
else
    echo "------------------------------------------"
    echo "Ошибка: Пользователь $USER не найден!"
fi

echo "=========================================="
