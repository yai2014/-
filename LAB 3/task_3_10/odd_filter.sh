echo "=========================================="
echo "           ЧИСЛОВОЙ ФИЛЬТР"
echo "=========================================="
echo "Вывод нечетных чисел от 1 до 20"
echo "Остановка при встрече числа 15"
echo "=========================================="

for i in {1..20}; do
    if [ $i -eq 15 ]; then
        echo "------------------------------------------"
        echo "Достигнуто число 15. Остановка программы."
        break
    fi
    
    if [ $((i % 2)) -eq 0 ]; then
        continue
    fi
    
    echo "Нечетное число: $i"
done

echo "=========================================="
echo "Программа завершена."
echo "=========================================="
