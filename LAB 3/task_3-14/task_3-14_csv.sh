#!/bin/bash

echo "=========================================="
echo "     АНАЛИЗ CSV-ФАЙЛА С ТОВАРАМИ"
echo "=========================================="

if [ ! -f "data.csv" ]; then
    echo "Ошибка: Файл data.csv не найден!"
    exit 1
fi

echo "Данные из файла data.csv:"
echo "------------------------------------------"
cat data.csv
echo "------------------------------------------"
echo ""

echo "1. Названия товаров:"
echo "------------------------------------------"
awk -F',' '{print "  " $2}' data.csv
echo "------------------------------------------"

echo ""
echo "2. Товары дороже 20:"
echo "------------------------------------------"
awk -F',' '$3 > 20 {print "  " $2 " - " $3 " руб."}' data.csv
count=$(awk -F',' '$3 > 20 {count++} END {print count}' data.csv)
[ $count -eq 0 ] && echo "  Нет товаров дороже 20"
echo "------------------------------------------"

echo ""
echo "3. Общая стоимость:"
echo "------------------------------------------"
total=$(awk -F',' '{sum += $3} END {print sum}' data.csv)
echo "Общая стоимость всех товаров: $total руб."
echo "------------------------------------------"

echo ""
echo "Дополнительная статистика:"
echo "------------------------------------------"
count=$(awk -F',' 'END {print NR}' data.csv)
echo "Количество товаров: $count"

max_price=$(awk -F',' 'NR==1{max=$3; name=$2} $3>max{max=$3; name=$2} END{print name, max}' data.csv)
echo "Самый дорогой товар: $max_price руб."

min_price=$(awk -F',' 'NR==1{min=$3; name=$2} $3<min{min=$3; name=$2} END{print name, min}' data.csv)
echo "Самый дешевый товар: $min_price руб."

avg_price=$(awk -F',' '{sum+=$3; count++} END {printf "%.2f", sum/count}' data.csv)
echo "Средняя цена товара: $avg_price руб."
echo "------------------------------------------"
echo "=========================================="
echo "Анализ завершён."
echo "=========================================="
EOF
