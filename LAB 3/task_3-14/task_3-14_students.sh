#!/bin/bash
echo "=========================================="
echo "     АНАЛИЗ ФАЙЛА students.txt"
echo "=========================================="

if [ ! -f "students.txt" ]; then
    echo "Ошибка: Файл students.txt не найден!"
    exit 1
fi
echo "1. Имена студентов:"
echo "------------------------------------------"
awk '{print $1}' students.txt
echo "------------------------------------------"echo ""
echo "2. Оценки студентов:"
echo "------------------------------------------"
awk '{print $2}' students.txt
echo "------------------------------------------"
echo ""
echo "3. Номер строки и имя студента:"
echo "------------------------------------------"
awk '{print NR, $1}' students.txt
echo "------------------------------------------"
echo ""
echo "Альтернативный вариант (с использованием cat -n):"
echo "------------------------------------------"
cat -n students.txt | awk '{print $1, $2}'
echo "------------------------------------------"

echo "=========================================="
echo "Анализ завершён."
echo "=========================================="

