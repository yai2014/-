#!/bin/bash
echo "=========================================="
echo "     АНАЛИЗ ЗАПОЛНЕНИЯ ДИСКОВ"
echo "=========================================="
if ! command -v df &> /dev/null; then
    echo "Ошибка: Команда df не найдена!"
    exit 1
fi
printf "%-20s %-10s %s\n" "Файловая система" "Использовано %" "Статус"
printf "%-20s %-10s %s\n" "--------------------" "----------" "----------"
df -h | awk 'NR>1 {
    # Удаляем символ % из 5-го столбца
    gsub(/%/, "", $5)
    
    # Форматируем вывод
    printf "%-20s %-10s ", $1, $5"%"
    
    # Проверяем процент заполнения
    if ($5 > 90) {
        print "КРИТИЧЕСКИ!"
        print "  ⚠️ ВНИМАНИЕ: Файловая система " $1 " заполнена на " $5 "%!"
    } else if ($5 > 80) {
        print "ВНИМАНИЕ!"
        print "  ⚠️ Предупреждение: " $1 " заполнена на " $5 "%"
    } else if ($5 > 70) {
        print "ПРЕДУПРЕЖДЕНИЕ!"
        print "  ⚠️ " $1 " заполнена на " $5 "%"
    } else {
        print "OK"
    }
}'

echo "=========================================="
echo "Анализ завершён."
echo "=========================================="
