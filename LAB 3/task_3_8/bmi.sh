#!/bin/bash

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BLUE='\033[0;34m'
NC='\033[0m'

clear

echo "=========================================="
echo "     АНАЛИЗАТОР МЕТАБОЛИЧЕСКОГО ИНДЕКСА"
echo "                (BMI / ИМТ)"
echo "=========================================="
echo ""

echo -n "Введите вашу массу (в кг, например: 75.5): "
read weight

echo -n "Введите ваш рост (в метрах, например: 1.75): "
read height

bmi=$(echo "scale=2; $weight / ($height * $height)" | bc)
bmi_rounded=$(echo "scale=0; $bmi / 1" | bc)

echo ""
echo "------------------------------------------"
echo -e "${GREEN}Результат расчёта:${NC}"
echo "Масса: $weight кг"
echo "Рост: $height м"
echo "Ваш ИМТ: $bmi (округлённо: $bmi_rounded)"
echo "------------------------------------------"

echo -n "Интерпретация: "

if (( $(echo "$bmi < 18.5" | bc -l) )); then
    echo -e "${BLUE}Недостаточная масса тела${NC}"
    echo "Рекомендация: Увеличьте калорийность питания."
elif (( $(echo "$bmi >= 18.5" | bc -l) )) && (( $(echo "$bmi < 25" | bc -l) )); then
    echo -e "${GREEN}Нормальная масса тела${NC}"
    echo "Рекомендация: Отлично! Поддерживайте форму."
elif (( $(echo "$bmi >= 25" | bc -l) )) && (( $(echo "$bmi < 30" | bc -l) )); then
    echo -e "${YELLOW}Избыточная масса тела (предожирение)${NC}"
    echo "Рекомендация: Увеличьте физическую активность."
else
    echo -e "${RED}Ожирение${NC}"
    echo "Рекомендация: Проконсультируйтесь с врачом."
fi

echo "=========================================="

