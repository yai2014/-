#!/bin/bash

check_root() {
    if [ "$EUID" -eq 0 ]; then
        echo "Успешно: Скрипт запущен от имени суперпользователя (root)"
        return 0
    else
        echo "ОШИБКА: Скрипт должен быть запущен от имени суперпользователя!"
        echo "Текущий EUID: $EUID (требуется 0)"
        echo "Пожалуйста, запустите скрипт с sudo:"
        echo "  sudo ./check_root.sh"
        exit 1
    fi
}

echo "=========================================="
echo "     ПРОВЕРКА ПРАВ СУПЕРПОЛЬЗОВАТЕЛЯ"
echo "=========================================="

check_root

echo ""
echo "Дальнейшее выполнение скрипта..."
echo "Скрипт успешно завершён."
echo "=========================================="
